def ensure(parent, tag, order):
    el = parent.find(qn("w:" + tag))
    if el is not None:
        return el
    el = OxmlElement("w:" + tag)
    idx = order.index(tag)
    for child in parent:
        name = child.tag.split("}")[1]
        if name in order and order.index(name) > idx:
            child.addprevious(el)
            return el
    parent.append(el)
    return el


def get_ppr(p):
    ppr = p.find(qn("w:pPr"))
    if ppr is None:
        ppr = OxmlElement("w:pPr")
        p.insert(0, ppr)
    return ppr


def get_rpr(r):
    rpr = r.find(qn("w:rPr"))
    if rpr is None:
        rpr = OxmlElement("w:rPr")
        r.insert(0, rpr)
    return rpr


def split_pieces(text):
    """Split text into (piece, is_rtl) pieces: Latin/number runs are LTR, everything else RTL."""
    out, pos = [], 0
    for m in LTR.finditer(text):
        core = m.group(0).rstrip(" .,:;")
        if m.start() > pos:
            out.append((text[pos:m.start()], True))
        out.append((core, False))
        pos = m.start() + len(core)
    if pos < len(text):
        out.append((text[pos:], True))
    return [(t, rtl) for t, rtl in out if t]


def rtl_paragraph(p):
    ppr = get_ppr(p)
    ensure(ppr, "bidi", PPR_ORDER)
    jc = ppr.find(qn("w:jc"))
    if jc is not None and jc.get(qn("w:val")) in ("left", "start", "right", "end"):
        ppr.remove(jc)   # default (start) alignment of a bidi paragraph is the right margin
    for r in list(p.iter(qn("w:r"))):
        t = r.find(qn("w:t"))
        if t is None:
            continue
        rpr = get_rpr(r)
        fonts = ensure(rpr, "rFonts", RPR_ORDER)
        fonts.set(qn("w:cs"), CS_FONT)
        if rpr.find(qn("w:b")) is not None:
            ensure(rpr, "bCs", RPR_ORDER)
        sz = rpr.find(qn("w:sz"))
        if sz is not None:
            ensure(rpr, "szCs", RPR_ORDER).set(qn("w:val"), sz.get(qn("w:val")))
        text = t.text or ""
        if not ARABIC.search(text):
            continue                      # pure Latin / numbers: an LTR run inside the RTL paragraph
        # Arabic text: one rtl run per Arabic stretch, plain (LTR) runs for numbers and Latin words,
        # so Word keeps "+2.1%", "p < 1e-40" or "(z = 4.7)" in reading order.
        prev = r
        for i, (piece, is_rtl) in enumerate(split_pieces(text)):
            nr = r if i == 0 else copy.deepcopy(r)
            nt = nr.find(qn("w:t"))
            nt.text = piece
            nt.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
            nrpr = nr.find(qn("w:rPr"))
            old = nrpr.find(qn("w:rtl"))
            if old is not None:
                nrpr.remove(old)
            if is_rtl:
                ensure(nrpr, "rtl", RPR_ORDER)
            if i:
                prev.addnext(nr)
            prev = nr


def translate_paragraph(par, segs):
    runs = [r for r in par.runs]
    groups = []
    for r in runs:
        b = bool(r.bold)
        if groups and groups[-1][0] == b:
            groups[-1][1].append(r)
        else:
            groups.append((b, [r]))
    if len(groups) != len(segs):
        raise ValueError(f"group mismatch ({len(groups)} vs {len(segs)}): {par.text[:60]}")
    for (b, rs), seg in zip(groups, segs):
        rs[0].text = seg
        for extra in rs[1:]:
            extra._r.getparent().remove(extra._r)


def main():
    doc = docx.Document(SRC)
    used = set()
    missing = []

    # ---- body paragraphs
    for par in doc.paragraphs:
        txt = par.text
        if not txt.strip():
            continue
        keys = [k for k in P if txt.startswith(k)]
        if not keys:
            missing.append(txt)
            continue
        k = max(keys, key=len)
        translate_paragraph(par, P[k])
        used.add(k)

    # ---- tables
    for t in doc.tables:
        tblpr = t._tbl.tblPr
        ensure(tblpr, "bidiVisual", TBLPR_ORDER)
        for row in t.rows:
            for cell in row.cells:
                for par in cell.paragraphs:
                    if not par.text.strip():
                        continue
                    new = cell_text(par.text)
                    if new != par.text:
                        rs = par.runs
                        rs[0].text = new
                        for extra in rs[1:]:
                            extra._r.getparent().remove(extra._r)

    # ---- RTL for every paragraph (body + tables)
    for p in doc.element.body.iter(qn("w:p")):
        rtl_paragraph(p)

    # ---- section direction
    for sect in doc.element.body.iter(qn("w:sectPr")):
        if sect.find(qn("w:bidi")) is None:
            el = OxmlElement("w:bidi")
            dg = sect.find(qn("w:docGrid"))
            if dg is not None:
                dg.addprevious(el)
            else:
                sect.append(el)

    # ---- complex-script font in document defaults
    rpr_default = doc.styles.element.find(qn("w:docDefaults")).find(qn("w:rPrDefault")).find(qn("w:rPr"))
    ensure(rpr_default, "rFonts", RPR_ORDER).set(qn("w:cs"), CS_FONT)
    lang = ensure(rpr_default, "lang", RPR_ORDER)
    lang.set(qn("w:bidi"), "ar-SA")

    # ---- figures: swap in Arabic showcase images
    by_hash = {}
    for f in (ROOT / "showcase").glob("*.png"):
        ar = ROOT / "showcase_ar" / f.name
        if ar.exists():
            by_hash[hashlib.md5(f.read_bytes()).hexdigest()] = ar
    swapped, kept = [], []
    for rel in doc.part.rels.values():
        if "image" in rel.reltype:
            part = rel.target_part
            ar = by_hash.get(hashlib.md5(part.blob).hexdigest())
            if ar:
                part._blob = ar.read_bytes()
                swapped.append(ar.name)
            else:
                kept.append(str(part.partname))
    WP = "{http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing}"
    for e in doc.element.body.iter(WP + "docPr"):
        d = e.get("descr", "")
        if e.get("id") in DESCR:
            e.set("descr", DESCR[e.get("id")])
        elif d.startswith("outputs/"):
            k = [k for k in P if d.startswith(k)]
            if k:
                e.set("descr", P[max(k, key=len)][0])

    doc.core_properties.title = "Shop Stats: تقرير تحليلات المتجر"
    doc.core_properties.language = "ar-SA"
    doc.save(DST)

    print("unused keys:", [k for k in P if k not in used])
    print("untranslated paragraphs:", missing)
    print("swapped:", sorted(swapped))
    print("kept original images:", sorted(kept))


if __name__ == "__main__":
    main()
