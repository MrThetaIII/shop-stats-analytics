RANGE = re.compile(r"\(([^()]+?) to ([^()]+?)\)")
ARABIC = re.compile(r"[؀-ۿ]")
# Left-to-right runs (numbers with sign/%/$, Latin words, formulas, paths) inside Arabic text are wrapped in
# LRE ... PDF so Word keeps "+2.1%", "p < 1e-40" or "|z| = 4.3" in reading order inside RTL paragraphs.
LTR = re.compile(r"[+\-−±$|]*[A-Za-z0-9À-ɏ][A-Za-z0-9À-ɏ .,:;%$+\-−±=<>|/\\&'’_]*")


def iso(s):
    if not ARABIC.search(s):
        return s
    def w(m):
        t = m.group(0)
        core = t.rstrip(" .,:;")
        return "‪" + core + "‬" + t[len(core):]
    return LTR.sub(w, s)


def cell_text(s):
    if s in C:
        return C[s]
    t = RANGE.sub(r"(من \1 إلى \2)", s).replace("(no control)", "(دون مجموعة ضابطة)")
    m = re.fullmatch(r"(\S+) to (\S+)", t)
    if m:
        t = f"من {m.group(1)} إلى {m.group(2)}"
    return t


